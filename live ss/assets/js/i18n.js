const langState = {
  get lang(){ let v = localStorage.getItem('ls_lang'); return v || 'ar'; },
  set lang(v){ localStorage.setItem('ls_lang', v); },
  get dir(){ return this.lang === 'ar' ? 'rtl' : 'ltr'; },
  other(){ return this.lang === 'ar' ? 'fr' : 'ar'; }
};

const I18n = {
  t(key){
    const d = DICT[langState.lang] || DICT.ar;
    return (d[key] !== undefined) ? d[key] : (DICT.ar[key] !== undefined ? DICT.ar[key] : key);
  },
  apply(){
    document.documentElement.lang = langState.lang;
    document.documentElement.dir = langState.dir;
    document.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = this.t(el.getAttribute('data-i18n')); });
    document.title = this.t('appName') + ' — ' + this.t('tagline');
    document.querySelectorAll('[data-lang-btn]').forEach(b => b.classList.toggle('active', b.getAttribute('data-lang-btn') === langState.lang));
  },
  mount(){
    this.apply();
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
      btn.addEventListener('click', ()=>{
        langState.lang = btn.getAttribute('data-lang-btn');
        this.apply();
        location.reload();
      });
    });
  }
};
window.I18n = I18n;
window.langState = langState;
window.DICT = DICT;